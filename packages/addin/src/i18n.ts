export type Lang = "da" | "en";
export type T = (key: keyof Dict, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const d = lang === "en" ? en : da;
  return (key, vars) => d[key].replace(/\{(\w+)\}/g, (_, k) => String(vars?.[k] ?? ""));
}

export const I18n = createContext<{ lang: Lang; t: T }>({ lang: "da", t: makeT("da") });
export const useI18n = () => useContext(I18n);
